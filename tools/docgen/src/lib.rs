    #[test]
    fn an_appended_status_reply_variant_shows_last_in_wire_md() {
        let root = rafka_mesh_audit::workspace_root();
        let copy = Copy::of(&root, "wire");
        let before = pages(&copy.0).unwrap();
        const STATUS: &str = "crates/rafka-node-rpc-contract/src/status.rs";
        const APPENDED: &str = "    /// Appended by the docgen cell.\n    DocgenAppended {\n        /// Its one field.\n        appended: u64,\n    },\n";
        copy.edit(STATUS, |s| {
            let start = s.find("pub enum StatusReply {").expect("StatusReply is declared");
            let mut depth = 0usize;
            let close = start
                + s[start..]
                    .char_indices()
                    .find(|&(_, c)| {
                        depth = match c {
                            '{' => depth + 1,
                            '}' => depth - 1,
                            _ => depth,
                        };
                        c == '}' && depth == 0
                    })
                    .expect("StatusReply closes")
                    .0;
            format!("{}{APPENDED}{}", &s[..close], &s[close..])
        });
        let after = pages(&copy.0).unwrap();
        let (b, a) = (page(&before, "wire.md"), page(&after, "wire.md"));
        let mut expected = variant_rows(b, "StatusReply");
        expected.push((expected.len().to_string(), "DocgenAppended".into()));
        assert_eq!(variant_rows(a, "StatusReply"), expected, "the appended variant is the last row, at the next position");
        // The wire page names no source line, so the inserted lines move nothing else: the page
        // differs only by StatusReply's count line and the two new rows.
        let gone: Vec<&str> = b.lines().filter(|l| !a.lines().any(|x| x == *l)).collect();
        let added: Vec<&str> = a.lines().filter(|l| !b.lines().any(|x| x == *l)).collect();
        assert_eq!(gone.len(), 1, "only StatusReply's variant count line changed: {gone:?}");
        assert!(gone[0].contains(&format!("{} variants", expected.len() - 1)), "{gone:?}");
        assert_eq!(added.len(), 3, "the count line, the variant row and its field row: {added:?}");
        assert!(added[0].contains(&format!("{} variants", expected.len())), "{added:?}");
        assert!(added[1].starts_with(&format!("| {} | **`DocgenAppended`** |", expected.len() - 1)), "{added:?}");
        assert!(added[2].starts_with(&format!("| {}.0 | `appended` | `u64` |", expected.len() - 1)), "{added:?}");
        for p in ["frames.md", "statuses.md", "spans.md", "config.md"] {
            assert_eq!(page(&before, p), page(&after, p), "{p} does not move for a wire variant");
        }
    }

    #[test]
    fn a_renamed_span_shows_in_spans_md() {
        let root = rafka_mesh_audit::workspace_root();
        let copy = Copy::of(&root, "spans");
        let emitters = rafka_mesh_audit::telemetry::emitters(&copy.0).unwrap();
        let line_of = |e: &rafka_mesh_audit::telemetry::Emitter| std::fs::read_to_string(copy.0.join(&e.file)).unwrap().lines().nth(e.line - 1).unwrap().to_string();
        let e = emitters
            .iter()
            .find(|e| emitters.iter().filter(|o| o.name == e.name).count() == 1 && line_of(e).matches(&format!("\"{}\"", e.name)).count() == 1)
            .expect("a span named once, by a literal on its own line");
        let before = pages(&copy.0).unwrap();
        let renamed = format!("{}.docgen-renamed", e.name);
        copy.edit(&e.file, |s| {
            s.lines()
                .enumerate()
                .map(|(i, l)| if i + 1 == e.line { l.replace(&format!("\"{}\"", e.name), &format!("\"{renamed}\"")) } else { l.to_string() })
                .collect::<Vec<_>>()
                .join("\n")
                + "\n"
        });
        let after = pages(&copy.0).unwrap();
        let row = |name: &str| format!("| `{name}` | `{}:{}` |", e.file, e.line);
        assert!(page(&before, "spans.md").contains(&row(&e.name)), "the span is listed at its site before");
        assert!(!page(&after, "spans.md").contains(&row(&e.name)), "the old name is gone after the rename");
        assert!(page(&after, "spans.md").contains(&row(&renamed)), "the new name is listed at the same site");
        assert_eq!(page(&before, "wire.md"), page(&after, "wire.md"), "a span rename does not move the wire page");
    }

    #[test]
    fn the_summary_lists_the_lifecycle_index_then_architecture_then_reference() {
        let docs = std::env::temp_dir().join(format!("rafka-docgen-summary-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&docs);
        let write = |rel: &str, text: &str| {
            let p = docs.join(rel);
            std::fs::create_dir_all(p.parent().unwrap()).unwrap();
            std::fs::write(p, text).unwrap();
        };
        write(
            "architecture/fabric-mesh-node-lifecycles.md",
            "# Lifecycles\n\n## Pages\n\n| page | owns |\n|---|---|\n| [Gossip](gossip.md#frames) | frames |\n| [States](lifecycles/states.md) | states |\n| [Missing](missing.md) | nothing |\n\n```text\n[not a link](ignored.md)\n```\n\n## Node workflows\n\n[node.start](lifecycles/node-start.md), [gossip again](gossip.md), [web](https://example.com/x.md)\n\n## Index\n\n[States](lifecycles/states.md)\n",
        );
        write("architecture/gossip.md", "# Gossip\n");
        write("architecture/lifecycles/states.md", "# States\n");
        write("architecture/lifecycles/node-start.md", "# node.start\n");
        write("architecture/ignored.md", "# Ignored by the fence, listed with the rest\n");
        write("architecture/zeta.md", "no heading\n");
        write("architecture/alpha.md", "# Alpha [draft]\n");
        write("eng/not-architecture.md", "# Not listed\n");
        let out = docs.join("reference/rdm");
        let pages = [Page { file: "wire.md", title: "Node RPC wire bodies", body: String::new() }, Page { file: "spans.md", title: "Spans", body: String::new() }];
        summary::write(&docs, &out, &pages).unwrap();
        let got = std::fs::read_to_string(docs.join("SUMMARY.md")).unwrap();
        let _ = std::fs::remove_dir_all(&docs);
        assert_eq!(
            got,
            format!(
                "{MARKER}\n# Summary\n\n[Lifecycles](architecture/fabric-mesh-node-lifecycles.md)\n\n# Pages\n\n- [Gossip](architecture/gossip.md)\n- [States](architecture/lifecycles/states.md)\n\n# Node workflows\n\n- [node.start](architecture/lifecycles/node-start.md)\n\n# Architecture\n\n- [Alpha \\[draft\\]](architecture/alpha.md)\n- [Ignored by the fence, listed with the rest](architecture/ignored.md)\n- [zeta](architecture/zeta.md)\n\n# Reference (generated)\n\n- [Node RPC wire bodies](reference/rdm/wire.md)\n- [Spans](reference/rdm/spans.md)\n"
            )
        );
    }
