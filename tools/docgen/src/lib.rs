    /// A copy of the RDM workspace's manifests and member `src/` trees, removed on drop.
    struct Copy(PathBuf);

    impl Copy {
        fn of(root: &Path, tag: &str) -> Self {
            let to = std::env::temp_dir().join(format!("rdm-docgen-{tag}-{}", std::process::id()));
            let _ = std::fs::remove_dir_all(&to);
            std::fs::create_dir_all(&to).unwrap();
            std::fs::copy(root.join("Cargo.toml"), to.join("Cargo.toml")).unwrap();
            for member in rafka_mesh_audit::legacy::workspace_members(root) {
                std::fs::create_dir_all(to.join(&member)).unwrap();
                std::fs::copy(root.join(&member).join("Cargo.toml"), to.join(&member).join("Cargo.toml")).unwrap();
                copy_tree(&root.join(&member).join("src"), &to.join(&member).join("src"));
            }
            Self(to)
        }

        fn edit(&self, file: &str, f: impl FnOnce(String) -> String) {
            let path = self.0.join(file);
            let text = std::fs::read_to_string(&path).unwrap();
            std::fs::write(&path, f(text)).unwrap();
        }

        fn findings(&self) -> Vec<String> {
            variant_docs::findings(&source::Workspace::load(&self.0).unwrap()).unwrap()
        }
    }

    impl Drop for Copy {
        fn drop(&mut self) {
            let _ = std::fs::remove_dir_all(&self.0);
        }
    }

    fn copy_tree(from: &Path, to: &Path) {
        std::fs::create_dir_all(to).unwrap();
        for e in std::fs::read_dir(from).unwrap().flatten() {
            let p = e.path();
            if p.is_dir() {
                copy_tree(&p, &to.join(e.file_name()));
            } else {
                std::fs::copy(&p, to.join(e.file_name())).unwrap();
            }
        }
    }

    fn page<'a>(pages: &'a [Page], file: &str) -> &'a str {
        &pages.iter().find(|p| p.file == file).unwrap_or_else(|| panic!("no page {file}")).body
    }

    /// The `| file | line |` cells of the first line of `file` that starts with `prefix`, read from
    /// the source.
    fn line_of(root: &Path, file: &str, prefix: &str) -> String {
        let text = std::fs::read_to_string(root.join(file)).unwrap();
        let line = text.lines().position(|l| l.starts_with(prefix)).unwrap_or_else(|| panic!("no line starting {prefix:?} in {file}")) + 1;
        format!("`{file}` | {line}")
    }

    /// The serialized variant idents of `enum name` in `file`, parsed straight from the source: the oracle.
    fn declared_variants(root: &Path, file: &str, name: &str) -> Vec<String> {
        let syntax = syn::parse_file(&std::fs::read_to_string(root.join(file)).unwrap()).unwrap();
        syntax
            .items
            .iter()
            .find_map(|i| match i {
                syn::Item::Enum(e) if e.ident == name => Some(e.variants.iter().map(|v| v.ident.to_string()).collect()),
                _ => None,
            })
            .unwrap_or_else(|| panic!("no enum {name} in {file}"))
    }

    /// The `/// ` doc lines directly above the line declaring `variant` inside `enum name` in `file`.
    fn variant_doc(root: &Path, file: &str, name: &str, variant: &str) -> Vec<String> {
        let text = std::fs::read_to_string(root.join(file)).unwrap();
        let lines: Vec<&str> = text.lines().collect();
        let start = lines.iter().position(|l| l.trim_start().starts_with(&format!("pub enum {name} "))).unwrap_or_else(|| panic!("no enum {name} in {file}"));
        let at = start + lines[start..].iter().position(|l| l.trim_start().starts_with(variant) && l.trim_start()[variant.len()..].starts_with([' ', ',', '{', '('])).unwrap_or_else(|| panic!("no variant {variant}"));
        let mut doc: Vec<String> = lines[..at].iter().rev().skip_while(|l| l.trim_start().starts_with("#[")).take_while(|l| l.trim_start().starts_with("///")).map(|l| l.trim().to_string()).collect();
        doc.reverse();
        doc
    }

    /// The texts of `line` that rafka-v2's doc citation gate reads as a citation, in its two forms
    /// (rafka-v2 scripts/doc_citations.py `CITE`, scripts/check-doc-symbols.py `SYMBOL_CITE`):
    /// a `:<digits>` after `<path>.<ext>`, or after a character that is not a word character, `/`
    /// or `.` (LINE); and `<path>.<ext>::<ident>` (a symbol citation). The oracle, written here
    /// from the gate's own patterns.
    fn gate_citations(line: &str) -> Vec<String> {
        const EXTS: [&str; 5] = ["rs", "json", "yaml", "sh", "py"];
        let path_char = |c: char| c.is_alphanumeric() || matches!(c, '_' | '/' | '.' | '-');
        let chars: Vec<char> = line.chars().collect();
        // Whether chars[..end] ends with `<path chars>+.<ext>`.
        let ends_with_path = |end: usize| {
            EXTS.iter().any(|ext| {
                let tail: Vec<char> = format!(".{ext}").chars().collect();
                end > tail.len() && chars[end - tail.len()..end] == tail[..] && path_char(chars[end - tail.len() - 1])
            })
        };
        let around = |i: usize, after: usize| chars[i.saturating_sub(40)..(i + after).min(chars.len())].iter().collect::<String>();
        let mut out = Vec::new();
        for i in (0..chars.len()).filter(|&i| chars[i] == ':') {
            if chars.get(i + 1).is_some_and(char::is_ascii_digit) {
                let after_free = i == 0 || !(chars[i - 1].is_alphanumeric() || matches!(chars[i - 1], '_' | '/' | '.'));
                if after_free || ends_with_path(i) {
                    out.push(format!("LINE: {}", around(i, 6)));
                }
            }
            if chars.get(i + 1) == Some(&':') && chars.get(i + 2).is_some_and(|c| c.is_ascii_alphabetic() || *c == '_') && ends_with_path(i) {
                out.push(format!("SYMBOL: {}", around(i, 12)));
            }
        }
        out
    }

    #[test]
    fn no_generated_page_carries_a_rafka_v2_citation_form() {
        let root = rafka_mesh_audit::workspace_root();
        let pages = pages(&root).unwrap();
        for p in &pages {
            let found: Vec<String> = p.body.lines().flat_map(gate_citations).collect();
            assert!(found.is_empty(), "{}: an RDM location is shown as columns, never a citation form: {:?}", p.file, &found[..found.len().min(5)]);
        }
        assert!(page(&pages, "spans.md").contains("| span | file | line |"), "spans.md keeps each site's line, in its own column");
        assert!(page(&pages, "config.md").contains("| name | file | line | in | via |"), "config.md keeps each site's line, in its own column");
    }

    #[test]
    fn two_runs_over_one_tree_write_the_same_bytes() {
        let root = rafka_mesh_audit::workspace_root();
        let (a, b) = (pages(&root).unwrap(), pages(&root).unwrap());
        assert_eq!(a.iter().map(|p| p.file).collect::<Vec<_>>(), ["spans.md", "config.md"]);
        for (x, y) in a.iter().zip(&b) {
            assert!(x.body.starts_with(MARKER), "{} begins with the marker", x.file);
            assert!(x.body.lines().count() > 20, "{} states the code, not only a title: {:?}", x.file, x.body);
            assert_eq!(x.body, y.body, "{} is the same bytes on a second run", x.file);
        }
    }

    #[test]
