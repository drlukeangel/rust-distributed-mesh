    #[test]
    fn a_renamed_span_shows_in_spans_md() {
        let root = rafka_mesh_audit::workspace_root();
        let copy = Copy::of(&root, "spans");
        let emitters = rafka_mesh_audit::telemetry::emitters(&copy.0).unwrap();
        let line_of = |e: &rafka_mesh_audit::telemetry::Emitter| std::fs::read_to_string(copy.0.join(&e.file)).unwrap().lines().nth(e.line - 1).unwrap().to_string();
        let e = emitters
            .iter()
            .find(|e| emitters.iter().filter(|o| o.name == e.name).count() == 1 && line_of(e).matches(&format!("\"{}\"", e.name)).count() == 1)
            .expect("a span named once, by a literal on its own line");
        let before = pages(&copy.0).unwrap();
        let renamed = format!("{}.docgen-renamed", e.name);
        copy.edit(&e.file, |s| {
            s.lines()
                .enumerate()
                .map(|(i, l)| if i + 1 == e.line { l.replace(&format!("\"{}\"", e.name), &format!("\"{renamed}\"")) } else { l.to_string() })
                .collect::<Vec<_>>()
                .join("\n")
                + "\n"
        });
        let after = pages(&copy.0).unwrap();
        let row = |name: &str| format!("| `{name}` | `{}` | {} |", e.file, e.line);
        assert!(page(&before, "spans.md").contains(&row(&e.name)), "the span is listed at its site before");
        assert!(!page(&after, "spans.md").contains(&row(&e.name)), "the old name is gone after the rename");
        assert!(page(&after, "spans.md").contains(&row(&renamed)), "the new name is listed at the same site");
        assert_eq!(page(&before, "config.md"), page(&after, "config.md"), "a span rename does not move the config page");
    }

    #[test]
    fn every_wire_body_frame_and_status_variant_states_its_position_and_serialized_name_in_its_doc() {
        let root = rafka_mesh_audit::workspace_root();
        let found = variant_docs::findings(&source::Workspace::load(&root).unwrap()).unwrap();
        assert!(found.is_empty(), "{} variants or ops differ from what their source implies:\n{}", found.len(), found.join("\n"));
        // The oracle, read straight from the source: StatusReply's variants each end with their index.
        let file = "crates/rdm-core/src/status.rs";
        for (i, v) in declared_variants(&root, file, "StatusReply").iter().enumerate() {
            assert_eq!(variant_doc(&root, file, "StatusReply", v).last().map(String::as_str), Some(format!("/// Position {i} on the wire.").as_str()), "StatusReply::{v}");
        }
        let doc = variant_doc(&root, "crates/rdm-core/src/digest.rs", "MemberStatus", "ConnectionsDeleting");
        assert_eq!(doc.last().map(String::as_str), Some("/// Position 2 on the wire; serialized as `connections-deleting`."), "a kebab-case status carried on the wire names its position and its serialized form");
        let doc = variant_doc(&root, "crates/rdm-transport/src/topology.rs", "Frame", "Digest");
        assert_eq!(doc.last().map(String::as_str), Some("/// Schema index 0, never a wire kind."), "a frame's index is never a wire kind");
    }

    #[test]
    fn an_appended_status_reply_variant_without_its_position_is_named() {
        let root = rafka_mesh_audit::workspace_root();
        let copy = Copy::of(&root, "appended");
        const STATUS: &str = "crates/rdm-core/src/status.rs";
        let next = declared_variants(&root, STATUS, "StatusReply").len();
        const APPENDED: &str = "    /// Appended by the docgen cell.\n    DocgenAppended {\n        /// Its one field.\n        appended: u64,\n    },\n";
        copy.edit(STATUS, |s| {
            let start = s.find("pub enum StatusReply {").expect("StatusReply is declared");
            let mut depth = 0usize;
            let close = start
                + s[start..]
                    .char_indices()
                    .find(|&(_, c)| {
                        depth = match c {
                            '{' => depth + 1,
                            '}' => depth - 1,
                            _ => depth,
                        };
                        c == '}' && depth == 0
                    })
                    .expect("StatusReply closes")
                    .0;
            format!("{}{APPENDED}{}", &s[..close], &s[close..])
        });
        assert_eq!(
            copy.findings(),
            [format!("{STATUS}: StatusReply::DocgenAppended owes the last doc paragraph \"Position {next} on the wire.\" (it ends \"Appended by the docgen cell.\")")],
            "only the appended variant is named, with the paragraph it owes"
        );
    }

