//! `rdm-docgen`: the reference pages that state what RDM's code IS, read from its source with `syn`
//! (no runtime reflection), written into this repository's `docs/reference/rdm/`.
//!
//! One reader per page, called by one workflow ([`pages`], [`run`]):
//!
//! ```text
//! spans.md     every span name rafka-mesh-audit's scanner finds, with file:line
//! config.md    every RDM_* / RAFKA_* env name and each place the source names it
//! ```
//!
//! The wire bodies, the gossip `Frame` and the statuses are stated on the types themselves (rustdoc):
//! [`variant_docs`] checks that each variant's doc comment carries its position and serialized name.
//! Output is deterministic: sorted everywhere.

pub mod config;
pub mod render;
pub mod source;
pub mod spans;
pub mod variant_docs;

use std::path::Path;

/// The first line of every generated page.
pub const MARKER: &str = "<!-- generated by rdm-docgen — do not edit -->";

/// One generated reference page.
pub struct Page {
    /// Its file name in the output directory.
    pub file: &'static str,
    /// Its title (the page's H1).
    pub title: &'static str,
    /// The whole page, beginning with [`MARKER`].
    pub body: String,
}

/// Read the RDM workspace at `root` and render the two reference pages.
pub fn pages(root: &Path) -> anyhow::Result<Vec<Page>> {
    let ws = source::Workspace::load(root)?;
    Ok(vec![
        Page { file: "spans.md", title: spans::TITLE, body: spans::page(root)? },
        Page { file: "config.md", title: config::TITLE, body: config::page(&ws)? },
    ])
}

/// The workflow: render the pages from `root` and write them into `out`.
pub fn run(root: &Path, out: &Path) -> anyhow::Result<()> {
    let pages = pages(root)?;
    std::fs::create_dir_all(out).map_err(|e| anyhow::anyhow!("creating {}: {e}", out.display()))?;
    for p in &pages {
        let path = out.join(p.file);
        std::fs::write(&path, &p.body).map_err(|e| anyhow::anyhow!("writing {}: {e}", path.display()))?;
    }
    Ok(())
}

